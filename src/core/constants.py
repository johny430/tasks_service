# Верхняя граница идентификаторов (PostgreSQL BIGINT). Больший id в пути отклоняется с 422,
# иначе asyncpg упал бы на переполнении и запрос завершился бы ошибкой 500.
MAX_BIGINT = 2**63 - 1

# Строка без NUL-символа (\x00): PostgreSQL не хранит его в текстовых полях и отвечает ошибкой,
# поэтому такие строки отклоняются валидацией с 422.
NO_NUL_PATTERN = r'^[^\x00]*$'
